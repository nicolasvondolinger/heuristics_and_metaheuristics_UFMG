#include <bits/stdc++.h>
#include <filesystem>

using namespace std;
using namespace filesystem;
using namespace chrono;
 
#define _ ios_base::sync_with_stdio(0); cin.tie(0);
#define all(a) (a).begin(), (a).end()
#define endl '\n'
#define ff first
#define ss second
#define pb push_back
 
typedef long long ll;
 
const int INF = 0x3f3f3f3f;
const ll LINF = 0x3f3f3f3f3f3f3f3fll;

int euclidean_distance(double x1, double x2, double y1, double y2){
    double x = x1 - x2, y = y1 - y2;
    return round(sqrt(x*x + y*y));
}

double pseudoeuclian_distance(double x1, double x2, double y1, double y2){
    double x = x1 - x2, y = y1 - y2;
    double r = sqrt((x*x + y*y)/10.0);
    return round(r);
}

vector<pair<double, double>> positions;
vector<vector<int>> graph, edgeWeights;

int n = 0;
random_device rd;
mt19937 gen(rd());

pair<vector<int>, ll> construct_solution(double alpha){
    vector<int> tour;
    vector<bool> visited(n, false);
    ll finalCost = 0;

    uniform_int_distribution<> dis_node(0, n-1);
    int beginNode = dis_node(gen), node = beginNode;
    tour.pb(node); visited[node] = true;

    for(int i = 1; i < n; i++){

        vector<pair<int, int>> candidates;
        int minCost = INF, maxCost = -1;

        for(int v = 0; v < n; v++)if(!visited[v]){
            int cost = edgeWeights[node][v];
            candidates.pb({cost, v});
            minCost = min(minCost, cost);
            maxCost = max(maxCost, cost);
        }

        // Restricted Candidate List
        vector<int> rcl;

        int limit = minCost + (int)(alpha * (maxCost-minCost));

        for(const auto &p: candidates){
            if(p.ff <= limit) rcl.pb(p.ss);
        }

        if(rcl.empty()){
            for(const auto &p: candidates){
                if(p.ff == minCost) rcl.pb(p.ss);
            }
        }

        uniform_int_distribution<> rclDis(0, rcl.size()-1);

        int chosenNode = rcl[rclDis(gen)];

        tour.pb(chosenNode); visited[chosenNode] = true;
        finalCost += edgeWeights[node][chosenNode];
        node = chosenNode;
    }

    finalCost += edgeWeights[node][beginNode];
    return {tour, finalCost};
}

void local_search(vector<int>& tour, ll& cost){

    bool improved = false;

    while(!improved){
        improved = true;

        for(int i = 0; i < n-1; i++){
            for(int j = i+1; j < n; j++){
                int u1 = tour[i];
                int v1 = tour[i+1];
                int u2 = tour[j];
                int v2 = tour[(j+1)%n];

                int currentCost = edgeWeights[u1][v1] + edgeWeights[u2][v2];
                int newCost = edgeWeights[u1][u2] + edgeWeights[v1][v2];

                ll delta = currentCost - newCost;

                if(delta > 0){

                    reverse(tour.begin() + i + 1, tour.begin() + j + 1);
                    cost -= delta;
                    improved = false;
                    continue;
                }
            }
        }
    }

}

int main(int argc, char* argv[]){ 
    string repoPath = "../instances/";
    ofstream outputFile("results.txt");

    for (const auto& entry : directory_iterator(repoPath)){
        string filename = entry.path().string();
        ifstream file(filename);

        if (!file.is_open()) {
            cerr << "Error: Could not open file " << filename << endl;
            return 1;
        }

        string line, keyword, value;
        string weightType;

        while (getline(file, line)) {
            istringstream iss(line); iss >> keyword;
            string discart; if(keyword[keyword.size()-1]!=':') iss >> discart;
            
            if (keyword == "TYPE:") {
                iss >> value;
                if (value != "TSP") {
                    cerr << "Error: Unsupported problem type: " << value << endl;
                    return 1;
                }
            } else if(keyword == "EDGE_WEIGHT_TYPE"){
                iss >> weightType;
                if(weightType != "EUC_2D" && weightType != "ATT"){
                    cerr << "Error: Unsupported edge weight type " << weightType << endl;
                    return 1;
                }
            } else if(keyword == "DIMENSION:"){
                iss >> n; 
                graph = vector<vector<int>>(n);
                positions = vector<pair<double, double>>(n);
                edgeWeights = vector<vector<int>>(n, vector<int>(n, INF));
            } else if(keyword == "NODE_COORD_SECTION"){
                while (getline(file, line)){
                    if (line == "EOF") break;
                    istringstream temp(line);
                    int p; double x, y; temp >> p >> x >> y;
                    positions[p-1].ff = x; positions[p-1].ss = y;
                }
            } else if (keyword == "NAME:" || keyword == "COMMENT:" || keyword == "DISPLAY_DATA_TYPE:") continue;
            else {
                cerr << "Error: Unsupported input type: " << keyword << " " << value << endl;
                return 1;
            }
        }

        for(int i = 0; i < n; i++){
            for(int j = 0; j < n; j++){
                if(i != j) graph[i].push_back(j);
            }
        }

        for (int i = 0; i < n; ++i) {
            for (int j = 0; j < graph[i].size(); j++) {  
                int w = graph[i][j];
                double x1 = positions[i].first;
                double y1 = positions[i].second;
                double x2 = positions[w].first;
                double y2 = positions[w].second;

                if(weightType=="EUC_2D") edgeWeights[i][w] = euclidean_distance(x1, x2, y1, y2);
                else edgeWeights[i][w] = pseudoeuclian_distance(x1, x2, y1, y2);
            }
        } 
        
        auto start = high_resolution_clock::now();

        ll ans = LINF; // Melhor custo encontrado para esta instância
        vector<int> best_tour; // Melhor tour encontrado

        // --- Parâmetros do GRASP ---
        int max_iterations = 100; // Número de iterações do GRASP
        double alpha = 0.25;       // Fator de aleatoriedade (0.0 = guloso, 1.0 = aleatório)

        for(int iter = 0; iter < max_iterations; iter++) {
            
            // 1. Fase de Construção
            pair<vector<int>, ll> constructed = construct_solution(alpha);
            vector<int> current_tour = constructed.first;
            ll current_cost = constructed.second;

            // 2. Fase de Busca Local
            local_search(current_tour, current_cost);
            
            // 3. Atualiza a melhor solução global (para esta instância)
            if (current_cost < ans) {
                ans = current_cost;
                best_tour = current_tour;
            }
        }

        auto end = high_resolution_clock::now();
        auto duration = duration_cast<milliseconds>(end - start);

        outputFile << filename.substr(13) <<": " << ans << " " << duration.count() << endl;

    }

    outputFile.close();
    exit(0);
}
